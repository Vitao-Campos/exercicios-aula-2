const temperatura = 31;
// fahrenheit = (celsius * 9/5) + 32
console.log (`a temperatura em celsius é: ${temperatura} °C`);
const fahrenheit = (temperatura * 9/5) + 32;
console.log (`a temperatura em fahrenheit é: ${fahrenheit} °F`);
// kelvin = celsius + 273.15
const kelvin = temperatura + 273.15;
console.log (`a temperatura em kelvin é: ${kelvin} K`);
